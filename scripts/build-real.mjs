// Build web/real.js: the on-chain records the demo can replay next to the scripted narrative.
//   node scripts/build-real.mjs
// Source txs (all on Studio, contract v3 / v2 as noted):
//  - ACCEPTED replay: v3 inquiry halden-mvf31ix5, round1 + round2 convene txs (leader record, votes, models)
//  - Model spread: v2 inquiry halden-mvf2dzg3, round1 + round2 convene txs, whose 4 consensus rotations ran 4
//    different models on identical inputs
import { writeFileSync, readFileSync } from 'fs'
import { join } from 'path'
import { accounts, client, loadState, ROOT } from './common.mjs'

const c = client(accounts()[0])
const dec = (x) => { const b = typeof x === 'string' ? x : x?.raw; if (!b) return null; const s = Buffer.from(b, 'base64').toString('utf8'); try { return JSON.parse(s.slice(s.indexOf('{'))) } catch { return null } }
const nice = (m) => (m ? String(m).replace('policy:prd-', '').replace('openai/', '').replace('google/', '') : 'no vote')
const slim = (rec) => ({
  ambiguity: rec.ambiguity, concordance: rec.concordance, agreed: rec.agreed, contested: rec.contested, unsupported: rec.unsupported,
  alignment: rec.alignment, flagged: rec.flagged,
  props: rec.props.map((p) => ({ index: p.index, weight: p.weight, cells: p.cells, affirm: p.affirm, deny: p.deny, divergence: p.divergence,
    status: p.status, lean: p.lean, clarity: p.clarity, cause: p.cause, crux: p.crux, decisive: p.decisive })),
})

async function accepted(hash) {
  const tx = await c.getTransaction({ hash })
  const cd = tx.consensus_data
  const lr = cd.leader_receipt[0]
  return {
    hash, status: tx.statusName, result: tx.result_name, rounds: Number(tx.num_of_rounds), leaderModel: nice(lr.node_config?.primary_model?.model),
    validators: cd.validators.map((v) => ({ model: nice(v.node_config?.primary_model?.model), vote: v.vote })),
    rec: slim(dec(lr.result)),
  }
}
async function spread(hash) {
  const tx = await c.getTransaction({ hash })
  return {
    hash, status: tx.statusName, result: tx.result_name,
    models: tx.consensus_history.consensus_results.map((cr, i) => {
      const lr = Array.isArray(cr.leader_result) ? cr.leader_result[0] : cr.leader_result
      return { rotation: i + 1, model: nice(lr?.node_config?.primary_model?.model), rec: slim(dec(lr?.result)),
        votes: (cr.validator_results ?? []).map((v) => v.vote) }
    }),
  }
}

const V3 = ['0x6539cd6ec626f7c99b45db42147ddba34d630c2af5c35a9fde531583e431d380', '0x7e63a8360ca9dc1dfc99cfed0c2ed54b6e794f6dfc571c48dddb64632c63678b'] // halden-mvf31ix5 round1, round2
const V2 = ['0xa596b2b9f437f41564236eb3980518380f5d172b1639a0aa3d78aad6032aad56', '0x0ec69d6b26bcff29e3204a5b374f1ca633b0ecfa929462e79dcfd14e2abdd3cd'] // halden-mvf2dzg3 round1, round2
const out = {
  contract: '0x58E8b84B0b55e9d4d33e5E973CF41D475919ECc7',
  note: 'Recorded from GenLayer Studio. Rounds replay v3 txs; spread replays v2 txs where every rotation used a different model.',
  rounds: [await accepted(V3[0]), await accepted(V3[1])],
  spread: [await spread(V2[0]), await spread(V2[1])],
  escrowObserved: { pct: 12, paid: 120000, of: 1000000, inquiry: 'halden-mvf31ix5', note: 'docs/ONCHAIN.md run 1' },
}
writeFileSync(join(ROOT, 'web', 'real.js'), '/* generated by scripts/build-real.mjs from GenLayer Studio transactions */\nwindow.REAL = ' + JSON.stringify(out) + ';\nif (typeof module !== "undefined") module.exports = window.REAL;\n')
console.log('rounds', out.rounds.map((r) => `${r.status}/${r.result} amb=${r.rec.ambiguity} leader=${r.leaderModel} votes=${r.validators.map((v) => v.vote).join(',')}`))
console.log('spread', out.spread.map((s) => s.models.map((m) => `${m.model}:${m.rec.ambiguity}`).join(' ')))
