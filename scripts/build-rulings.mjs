// Build web/rulings.js from recorded Studio results: the ruling and the gate claim the demo cites.
//   node scripts/build-rulings.mjs
import { readFileSync, writeFileSync } from 'fs'
import { join } from 'path'
import { accounts, client, ROOT } from './common.mjs'

const easy = JSON.parse(readFileSync(join(ROOT, 'scripts', 'rulings-easy.json'), 'utf8'))
const gate = JSON.parse(readFileSync(join(ROOT, 'scripts', 'gate-result.json'), 'utf8')).runs.at(-1)
const row = easy.results.find((r) => r.prop === 0)
const rpc = async (method, params) => (await (await fetch('https://studio.genlayer.com/api', { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, params }) })).json())
const list = (await rpc('sim_getTransactionsForAddress', [accounts(8)[0].address])).result ?? []
const dec = (t) => { try { return Buffer.from(t.data?.calldata ?? '', 'base64').toString('utf8') } catch { return '' } }
// pick the ruling for proposition 0 by reading the `prop` field out of each candidate transaction's on-chain result
const c = client(accounts(8)[0])
const candidates = list.filter((t) => dec(t).includes(easy.inquiry) && dec(t).includes('request_ruling'))
let tx = null
for (const t of candidates) {
  const full = await c.getTransaction({ hash: t.hash })
  const lr = full.consensus_data?.leader_receipt?.[0]; const raw = typeof lr?.result === 'string' ? lr.result : lr?.result?.raw
  const text = raw ? Buffer.from(raw, 'base64').toString('utf8') : ''
  if (/"prop": 0,/.test(text) && full.statusName !== 'UNDETERMINED') { tx = t.hash; break }
}
if (!tx) throw new Error('could not find the ruling transaction for proposition 0')
const out = {
  RULING: {
    prop: 6, verdict: row.verdict, reason: row.reason, tx, inquiry: easy.inquiry, contract: easy.address,
    clause_short: "Clause 14.2: 'Port closure' means a formal order of the harbour master or port authority suspending berthing or cargo operations. A vessel waiting in an anchorage queue without such an order is not subject to a port closure.",
    note: `Real Studio ruling on the same question and clause text; ${row.rounds} consensus round, ${row.secs}s.`,
  },
  GATE: { address: gate.gate, concordance: gate.concordance, tx: gate.claimTx, pct: gate.release_pct, note: `a policy requiring a ruled proposition, funded with ${Number(gate.gained).toLocaleString('en-US')} wei and paid in full` },
}
writeFileSync(join(ROOT, 'web', 'rulings.js'), '/* generated by scripts/build-rulings.mjs from GenLayer Studio transactions */\nwindow.RULING = ' + JSON.stringify(out.RULING) + ';\nwindow.GATE = ' + JSON.stringify(out.GATE) + ';\n')
console.log(JSON.stringify({ tx, verdict: row.verdict, gateTx: gate.claimTx, pct: gate.release_pct }))
